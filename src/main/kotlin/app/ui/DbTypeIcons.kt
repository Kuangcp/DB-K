/**
 * 数据源类型 → 品牌图标。穷尽 `when`：新增 [DbType] 漏配图标编译不过
 * （与 [DbType.category] / [DbType.protocol] 同一套约定）。
 */
val DbType.brandIcon: ImageVector
    get() = when (this) {
        DbType.POSTGRES -> BrandIcons.Postgres
        DbType.MYSQL -> BrandIcons.Mysql
        DbType.MARIADB -> BrandIcons.Mariadb
        DbType.SQLITE -> BrandIcons.Sqlite
        DbType.H2 -> BrandIcons.H2
        DbType.H2LOCAL -> BrandIcons.H2Local
        DbType.CLICKHOUSE -> BrandIcons.Clickhouse
        DbType.SQLSERVER -> BrandIcons.Sqlserver
        DbType.ORACLE -> BrandIcons.Oracle
        DbType.REDIS -> BrandIcons.Redis
        DbType.ELASTICSEARCH -> BrandIcons.Elasticsearch
    }
