/**
 * 数据源品牌图标：多数取各产品的公开识别隐喻（大象 / 海豚 / 立方 / 分段圆环 …），
 * 按统一几何语言重绘 —— 24×24 画布、图形收在 ~18u 光学框内、全部实心单路径、
 * 只用 M/L/C/Q/Z 绝对指令，靠 [ImageVector] 的 NonZero 填充规则做「并集」
 * （同绕向子形状重叠即融合，**反绕向**子形状即镂空）。
 * 例外：[BrandIcons.Redis] 直接内嵌官方字形（见其注释）。
 *
 * 不引入 SVG 解析/图标库，也不内嵌官方 logo 文件：
 * 官方图形在 15dp（树里连接行的实际尺寸）下多数不可读，且 H2 / SQL Server / Oracle
 * 根本没有公开可用的字形，混用必然风格割裂。
 *
 * 品牌色由调用方通过 `Icon(tint = …)` 传入（树里也上色，见 [tree.TypeBadge]），
 * 这里的 fill 只是占位黑（与 [DbIcons] 一致）。
 */
